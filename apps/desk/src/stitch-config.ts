/**
 * Generates Stitch's stitch.toml for the desk from corridors.ts. Mirrors Stitch's own Celo
 * templates (textile-stitch src/setup/templates/w{ars,brl}-usdt-celo.toml, read 2026-10-15):
 * same chain block and reactor, with our feed per pool, fixed caps (never "max": both pools
 * share the USDT, and "max" would let each pledge all of it), and our spreads.
 * The [rfq] block is written by Stitch's own Connect step, so it is not generated here. Pure.
 */
import { CONTRACTS, TOKENS } from "@arbolito/config";
import type { Corridor } from "./corridors";

export interface StitchOptions {
  /** Base URL Stitch reaches the feed on, e.g. http://desk-feed.railway.internal:8790 */
  feedBaseUrl: string;
  rpcUrl?: string;
  /** Our feed refreshes every ~10 s; a breaker hold ages out after this. */
  stalenessSecs?: number;
  /** Smallest slice in USDT atomic units (6 dp). */
  minSliceUsdt?: bigint;
  /** Pairs whose buy side is switched off (inventory cap reached); their sell side still quotes. */
  buyOff?: ReadonlySet<string>;
  /** Per pair, the USDT the buy side may offer (limits.ts buySizes); under one slice means off. Default: buyCapUsdt. */
  buySize?: ReadonlyMap<string, bigint>;
  /** The maker registration; when given, the [rfq] block is written here instead of by `stitch connect`. */
  rfq?: { streamUrl: string; makerId: string; validationContract: string };
}

export const feedUrl = (base: string, pair: string) => `${base.replace(/\/$/, "")}/feed/${pair}`;

export function stitchToml(all: readonly Corridor[], o: StitchOptions): string {
  // Only funded corridors are quoted; the rest are priced by the feed but never offered.
  const corridors = all.filter((c) => c.live);
  if (!corridors.length) throw new Error("no live corridors");
  const slice = (o.minSliceUsdt ?? 5_000_000n).toString();
  const lines: string[] = [
    "# Generated by apps/desk (pnpm desk:stitch-config). Change apps/desk/src/corridors.ts, not this file.",
    "# The wallet key is NOT here: STITCH_PRIVATE_KEY(_FILE). [rfq] is written by `stitch connect`.",
    "modules_enabled = false",
    "chain_id = 42220",
    `rpc_url = "${o.rpcUrl ?? "https://forno.celo.org"}"`,
    'indexer_url = "https://api.textilecredit.com"',
    `permit2 = "${CONTRACTS.permit2}"`,
    `reactor = "${CONTRACTS.textile.limitOrderReactor}"  # SETTLEMENT_V3_FILLER_REACTOR (Celo), as in Stitch's template`,
    "tick_interval_secs = 5",
    "book_enabled = false  # RFQ only, no public ladder",
    "",
    "[feed]",
    `url = "${feedUrl(o.feedBaseUrl, corridors[0]!.pair)}"`,
    `staleness_secs = ${o.stalenessSecs ?? 20}`,
  ];
  for (const c of corridors) {
    const size = o.buySize?.get(c.pair) ?? c.buyCapUsdt;
    const buyOff = o.buyOff?.has(c.pair) || size < BigInt(slice);
    lines.push(
      "",
      "[[pools]]",
      `# ${c.soft} / USDT`,
      `collateral = "${TOKENS[c.soft].address}"`,
      `collateral_decimals = ${TOKENS[c.soft].decimals}`,
      `debt = "${TOKENS.USDT.address}"`,
      `debt_decimals = ${TOKENS.USDT.decimals}`,
      `feed_url = "${feedUrl(o.feedBaseUrl, c.pair)}"`,
      ...(buyOff
        ? ["# buy side off: inventory cap reached (apps/desk/src/limits.ts)"]
        : [`buy_offset_bps = ${c.buyOffsetBps}`, `buy_total_liquidity_debt = "${size < c.buyCapUsdt ? size : c.buyCapUsdt}"`, `buy_min_slice_debt = "${slice}"`, "buy_max_orders = 4"]),
      `sell_offset_bps = ${c.sellOffsetBps}`,
      `sell_total_liquidity_collateral = "${c.sellCapSoft}"`,
      `sell_min_slice_debt = "${slice}"`,
      "sell_max_orders = 4",
      "ttl_secs = 120",
      `corridor_network = "Celo"`,
    );
  }
  if (o.rfq) lines.push("", "[rfq]", "enabled = true", `url = "${o.rfq.streamUrl}"`, `maker_id = "${o.rfq.makerId}"`, `validation_contract = "${o.rfq.validationContract}"`);
  return lines.join("\n") + "\n";
}
