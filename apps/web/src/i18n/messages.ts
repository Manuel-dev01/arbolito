import type { Locale } from "../lib/format";

/**
 * UI copy. Spanish (es-AR, "vos") is the source; pt-BR and en mirror its shape.
 * Keep crypto jargon out of the first layer: amounts in the user's currency, chain details below.
 */

export type Lang = "es" | "pt" | "en";
export const LANGS: Lang[] = ["es", "pt", "en"];
export const LOCALE: Record<Lang, Locale> = { es: "es-AR", pt: "pt-BR", en: "en-US" };
export const LANG_LABEL: Record<Lang, string> = { es: "Español", pt: "Português", en: "English" };

export function getLang(value: string | string[] | undefined): Lang {
  const v = Array.isArray(value) ? value[0] : value;
  return v === "pt" || v === "en" ? v : "es";
}

/** Appends ?lang= for non-default languages so links keep the reader's language. */
export function withLang(href: string, lang: Lang): string {
  if (lang === "es") return href;
  const [path, hash] = href.split("#");
  return `${path}${path!.includes("?") ? "&" : "?"}lang=${lang}${hash ? `#${hash}` : ""}`;
}

